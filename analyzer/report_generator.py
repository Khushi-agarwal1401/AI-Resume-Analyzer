"""Builds the downloadable PDF analysis report (issue #19)."""

from datetime import date

from fpdf import FPDF

PURPLE = (112, 84, 217)
TEXT = (40, 40, 60)

# Highest mark for each score part (same numbers as score_limits in result.html)
MAX_MARKS = {
    "Contact Information": 10, "Professional Summary": 10,
    "Technical Skills": 20, "Education": 15,
    "Experience": 15, "Projects": 20, "Readability": 10,
}


def _write(pdf, text):
    # The built-in PDF font only knows Latin-1 characters, others become "?"
    text = str(text).encode("latin-1", "replace").decode("latin-1")
    pdf.multi_cell(0, 6, text, new_x="LMARGIN", new_y="NEXT")


def _heading(pdf, title):
    pdf.ln(5)
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(*PURPLE)
    pdf.cell(0, 8, title, new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(*PURPLE)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(3)
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(*TEXT)


def _score_section(pdf, data):
    _heading(pdf, "Overall Resume Score")
    pdf.set_font("Helvetica", "B", 26)
    pdf.cell(0, 14, f"{data.get('score', 0)} / 100", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 11)

    for name, marks in data.get("breakdown", {}).items():
        top = MAX_MARKS.get(name, 10)
        pdf.cell(60, 7, name)
        x, y = pdf.get_x(), pdf.get_y() + 2
        pdf.set_fill_color(230, 226, 245)
        pdf.rect(x, y, 80, 3, "F")                              # empty bar
        pdf.set_fill_color(*PURPLE)
        pdf.rect(x, y, 80 * min(marks / top, 1), 3, "F")        # filled part
        pdf.set_x(x + 85)
        pdf.cell(0, 7, f"{marks} / {top}", new_x="LMARGIN", new_y="NEXT")


def build_report(data):
    """Return the report as PDF bytes. Optional parts are skipped if missing."""
    pdf = FPDF()
    pdf.add_page()

    # Title band
    pdf.set_fill_color(*PURPLE)
    pdf.rect(0, 0, pdf.w, 30, "F")
    pdf.set_xy(pdf.l_margin, 8)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Helvetica", "B", 20)
    pdf.cell(0, 10, "Resume Analysis Report", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(0, 6, "Generated on " + date.today().strftime("%d %B %Y"))
    pdf.set_y(34)
    pdf.set_text_color(*TEXT)

    _score_section(pdf, data)

    _heading(pdf, "Skills Detected")
    _write(pdf, ", ".join(data.get("skills", [])) or "No matching skills detected.")

    _heading(pdf, "Suggestions")
    for tip in data.get("suggestions", []):
        _write(pdf, "- " + tip)

    match = data.get("job_match") or {}
    if match.get("has_job_description"):
        _heading(pdf, "Job Description Match")
        _write(pdf, f"{match.get('match_percentage', 0)}% match: "
                    f"{match.get('total_matching', 0)} of "
                    f"{match.get('total_required', 0)} required skills found.")
        _write(pdf, "Matching skills: " + (", ".join(match.get("matching_skills", [])) or "None"))
        if match.get("semantically_related_skills"):
            semantic_items = [
                f"{s['required_skill']} (~ {s['matched_skill']}, {s.get('similarity', 0)}%)"
                for s in match["semantically_related_skills"]
            ]
            _write(pdf, "Semantically related skills: " + ", ".join(semantic_items))
        _write(pdf, "Missing skills: " + (", ".join(match.get("missing_skills", [])) or "None"))

    pdf.ln(8)
    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(120, 120, 140)
    _write(pdf, "Generated by AI Resume Analyzer. Scores and matches are based "
                "only on the text of your resume.")

    return bytes(pdf.output())